public class RestoranBilgisi {
    private int id;
    private String restoranAdi;
    private String adres;
    private String telefon;
    private String email;
    private String vergiNo;
    private String calismaSaatleri;

    public int getId() { return id; }
    public void setId(int id) { this.id = id; }

    public String getRestoranAdi() { return restoranAdi; }
    public void setRestoranAdi(String restoranAdi) { this.restoranAdi = restoranAdi; }

    public String getAdres() { return adres; }
    public void setAdres(String adres) { this.adres = adres; }

    public String getTelefon() { return telefon; }
    public void setTelefon(String telefon) { this.telefon = telefon; }

    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }

    public String getVergiNo() { return vergiNo; }
    public void setVergiNo(String vergiNo) { this.vergiNo = vergiNo; }

    public String getCalismaSaatleri() { return calismaSaatleri; }
    public void setCalismaSaatleri(String calismaSaatleri) { this.calismaSaatleri = calismaSaatleri; }
}
